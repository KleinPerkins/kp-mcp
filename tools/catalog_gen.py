"""Generate the kit catalog dashboard (docs/CATALOG.md) from the live registry.

Run::

    uv run python -m tools.catalog_gen
    # or: uv run python tools/catalog_gen.py

The catalog is the workspace-level dashboard of every kit: surfaces, op count,
service count, version, and coverage context. It is DERIVED from each kit's
registry (the single source of truth) so it can never drift from the shipped
ops. Re-running is deterministic (sorted, stable formatting); the CI determinism
gate runs it twice and asserts a zero ``git diff``.

What "op" and "service" mean here (registry-derived, no hand-maintained number):

* ``op``      — one registered ``OpSpec`` (== one generated operation card and schema).
* ``service`` — a dotted-name namespace (``<service>.<op>``) that is backed by a
  real external API. A namespace whose ops are ALL composition recipes (every op
  carries a truthy ``recipe`` attribute, e.g. ``recipes.*``) is a cross-service
  COMPOSITE, not a service, and is counted separately.
* ``meta-tool`` — an optional synthetic MCP discovery tool declared by a kit's
  generated schema manifest; it is not an OpSpec and does not inflate op counts.

Outputs:
  docs/CATALOG.md                  — full generated dashboard.
  docs/ECOSYSTEM.md                — the counts inside the catalog sentinel block.
"""
from __future__ import annotations

import importlib
import json
import sys
import tomllib
from pathlib import Path
from typing import Any

_ECOSYSTEM_START = "<!-- catalog:counts:start (generated by tools/catalog_gen.py — do not edit by hand) -->"
_ECOSYSTEM_END = "<!-- catalog:counts:end -->"


def _workspace_root() -> Path:
    return Path(__file__).resolve().parent.parent


def _kit_dirs(root: Path) -> list[Path]:
    """Return workspace kit directories (``*-kit``) that have a pyproject.toml."""
    return sorted(
        d
        for d in root.iterdir()
        if d.is_dir() and d.name.endswith("-kit") and (d / "pyproject.toml").is_file()
    )


def _package_name(kit_dir: Path) -> str:
    """Resolve the import package under ``<kit>/src/<pkg>/``."""
    src = kit_dir / "src"
    for child in sorted(src.iterdir()):
        if child.is_dir() and (child / "__init__.py").is_file():
            return child.name
    raise RuntimeError(f"No importable package under {src}")


def _project_version(kit_dir: Path) -> str:
    data = tomllib.loads((kit_dir / "pyproject.toml").read_text(encoding="utf-8"))
    return str(data.get("project", {}).get("version", "0.0.0"))


def _has_mcp(pkg: str) -> bool:
    try:
        importlib.import_module(f"{pkg}.mcp")
        return True
    except ModuleNotFoundError:
        return False


def _has_cli(kit_dir: Path) -> bool:
    data = tomllib.loads((kit_dir / "pyproject.toml").read_text(encoding="utf-8"))
    return bool(data.get("project", {}).get("scripts"))


def _coverage_for(kit_dir: Path, root: Path, sole_kit: bool) -> dict[str, Any] | None:
    """Load optional coverage context for a kit.

    Prefers ``<kit>/docs/coverage.json``; falls back to the workspace
    ``docs/coverage.json`` only when this is the sole kit (the google-kit case).
    """
    local = kit_dir / "docs" / "coverage.json"
    if local.is_file():
        return json.loads(local.read_text(encoding="utf-8"))
    shared = root / "docs" / "coverage.json"
    if sole_kit and shared.is_file():
        return json.loads(shared.read_text(encoding="utf-8"))
    return None


def _kit_stats(kit_dir: Path, root: Path, sole_kit: bool) -> dict[str, Any]:
    """Compute the registry-derived dashboard stats for one kit."""
    pkg = _package_name(kit_dir)
    src = str(kit_dir / "src")
    if src not in sys.path:
        sys.path.insert(0, src)
    try:
        importlib.import_module(pkg)
        registry = importlib.import_module(f"{pkg}.registry")
    except ModuleNotFoundError as exc:
        raise RuntimeError(
            f"{kit_dir.name} must provide an importable {pkg}.registry module"
        ) from exc
    specs = list(registry.all_specs())

    ns_ops: dict[str, list[Any]] = {}
    for spec in specs:
        ns_ops.setdefault(spec.name.split(".")[0], []).append(spec)

    services: list[str] = []
    composites: list[str] = []
    for ns, ops in ns_ops.items():
        if ops and all(getattr(op, "recipe", None) for op in ops):
            composites.append(ns)
        else:
            services.append(ns)
    services.sort()
    composites.sort()

    surfaces = []
    if _has_cli(kit_dir):
        surfaces.append("CLI")
    if _has_mcp(pkg):
        surfaces.append("MCP")

    schema_manifest = kit_dir / "docs" / "schemas" / "_manifest.json"
    meta_tools: dict[str, str] = {}
    if schema_manifest.is_file():
        manifest = json.loads(schema_manifest.read_text(encoding="utf-8"))
        declared = manifest.get("meta_tools", {})
        if isinstance(declared, dict):
            meta_tools = {str(key): str(value) for key, value in declared.items()}

    return {
        "name": kit_dir.name,
        "package": pkg,
        "version": _project_version(kit_dir),
        "surfaces": " + ".join(surfaces) or "—",
        "op_count": len(specs),
        "service_count": len(services),
        "services": services,
        "composites": composites,
        "ns_counts": {ns: len(ops) for ns, ops in ns_ops.items()},
        "meta_tools": meta_tools,
        "coverage": _coverage_for(kit_dir, root, sole_kit),
    }


def _coverage_block(stats: dict[str, Any]) -> str:
    """Render the coverage-reconciliation paragraph, or an empty string."""
    cov = stats["coverage"]
    if not cov:
        return ""
    summary = cov.get("summary", {})
    covered = summary.get("covered_count")
    total = summary.get("total")
    if covered is None:
        return ""
    ops = stats["op_count"]
    composite_ops = sum(
        n for ns, n in stats["ns_counts"].items() if ns in set(stats["composites"])
    )
    delta = ops - covered
    lines = [
        "**Coverage reconciliation**",
        "",
        f"- **Shipped ops (registry / cards / schemas): {ops}** — the authoritative kit op count.",
        f"- **Covered legacy capabilities (`coverage.json`): {covered}**"
        + (f" of {total} surveyed" if total is not None else "")
        + " — a different denominator (legacy-surface coverage, not shipped ops).",
        f"- The {abs(delta)}-op gap is intrinsic: {composite_ops} cross-service `recipes` ops "
        "are not legacy-capability rows, while a small number of legacy capabilities are folded "
        "into existing ops (routed behaviours) rather than getting their own card. Both numbers "
        "are internally consistent; the catalog headline uses shipped ops.",
    ]
    return "\n".join(lines) + "\n\n"


def _service_table(stats: dict[str, Any]) -> str:
    rows = [
        "| Namespace | Ops | Kind |",
        "|-----------|-----|------|",
    ]
    composite_set = set(stats["composites"])
    for ns in sorted(stats["ns_counts"]):
        kind = "composite (cross-service recipes)" if ns in composite_set else "service"
        rows.append(f"| `{ns}` | {stats['ns_counts'][ns]} | {kind} |")
    rows.append(f"| **Total** | **{stats['op_count']}** | — |")
    return "\n".join(rows)


def _count_phrase(stats: dict[str, Any]) -> str:
    """Bare 'N ops across M services (+ K cross-service recipes)' phrase."""
    extra = ""
    if stats["composites"]:
        composite_ops = sum(stats["ns_counts"][ns] for ns in stats["composites"])
        noun = "recipe" if composite_ops == 1 else "recipes"
        extra = f" (+ {composite_ops} cross-service {noun})"
    service_noun = "service" if stats["service_count"] == 1 else "services"
    return f"{stats['op_count']} ops across {stats['service_count']} {service_noun}{extra}"


def _headline(stats: dict[str, Any]) -> str:
    return f"**{_count_phrase(stats)}.**"


def _artifact_count_line(stats: dict[str, Any]) -> str:
    line = (
        f"Operation doc cards + MCP schemas: {stats['op_count']} each, generated "
        f"from the registry (`{stats['package']}.docgen_gen` / "
        f"`{stats['package']}.schema_gen`)."
    )
    meta_count = len(stats["meta_tools"])
    if meta_count:
        noun = "meta-tool" if meta_count == 1 else "meta-tools"
        line += f" Plus {meta_count} generated MCP {noun}: " + ", ".join(
            f"`{name}`" for name in sorted(stats["meta_tools"])
        ) + "."
    return line


def render_catalog(all_stats: list[dict[str, Any]]) -> str:
    """Render the full docs/CATALOG.md content."""
    out: list[str] = [
        "# Kit Catalog",
        "",
        "Inventory of all kits in the kp-mcp workspace.",
        "",
        "> Generated by `tools/catalog_gen.py` from each kit's registry — do not edit by",
        "> hand. Run `uv run python -m tools.catalog_gen`; the CI determinism gate keeps",
        "> it in sync with the shipped ops.",
        "",
        "---",
        "",
        "## Kit inventory",
        "",
        "| Kit | Surfaces | Services | Ops | Coverage | Version |",
        "|-----|----------|----------|-----|----------|---------|",
    ]
    for s in all_stats:
        out.append(
            f"| [`{s['name']}`](#{s['name']}) | {s['surfaces']} | {s['service_count']} "
            f"| {s['op_count']} | [COVERAGE.md](COVERAGE.md) | {s['version']} |"
        )
    out += ["", "---", "", "## Aggregate dashboards", ""]

    for s in all_stats:
        out += [
            f"### {s['name']}",
            "",
            _headline(s),
            "",
            f"Package `{s['package']}` · surfaces {s['surfaces']} · version {s['version']}.",
            "",
            _service_table(s),
            "",
        ]
        cov = _coverage_block(s)
        if cov:
            out.append(cov.rstrip("\n"))
            out.append("")
        out += [
            _artifact_count_line(s),
            "",
            f"- Capability index: [`{s['name']}/docs/INDEX.md`](../{s['name']}/docs/INDEX.md)",
            f"- Schema manifest: [`{s['name']}/docs/schemas/_manifest.json`](../{s['name']}/docs/schemas/_manifest.json)",
            f"- Safety rule: [`{s['name']}/rules/{s['name']}-mcp-safety.mdc`](../{s['name']}/rules/{s['name']}-mcp-safety.mdc)",
            "",
        ]

    out += [
        "---",
        "",
        "## Adding a kit to this catalog",
        "",
        "Kits are discovered automatically — any `*-kit` workspace member with a registry",
        "is picked up by the generator. To register a new kit:",
        "",
        "1. Scaffold it from [`template/`](../template/) (see [dev/MCP-UTILITY-TEMPLATE.md](dev/MCP-UTILITY-TEMPLATE.md)).",
        "2. Run `uv run python -m tools.catalog_gen` to regenerate this dashboard.",
        "3. Commit the regenerated `CATALOG.md`; CI determinism keeps it honest.",
        "",
    ]
    return "\n".join(out) + "\n"


def render_ecosystem_counts(all_stats: list[dict[str, Any]]) -> str:
    """Render the content for the ECOSYSTEM.md catalog sentinel block."""
    return "\n".join(f"- `{s['name']}` — {_count_phrase(s)}." for s in all_stats)


def _splice_sentinel(text: str, payload: str) -> str:
    start = text.index(_ECOSYSTEM_START) + len(_ECOSYSTEM_START)
    end = text.index(_ECOSYSTEM_END)
    return text[:start] + "\n" + payload + "\n" + text[end:]


def generate(*, root: Path | None = None) -> None:
    """Write docs/CATALOG.md and update the ECOSYSTEM.md counts block."""
    root = root or _workspace_root()
    kits = _kit_dirs(root)
    sole = len(kits) == 1
    all_stats = [_kit_stats(k, root, sole) for k in kits]

    catalog = root / "docs" / "CATALOG.md"
    catalog.parent.mkdir(parents=True, exist_ok=True)
    catalog.write_text(render_catalog(all_stats), encoding="utf-8")
    print(f"Generated {catalog} ({len(all_stats)} kit(s))", file=sys.stderr)

    ecosystem = root / "docs" / "ECOSYSTEM.md"
    if ecosystem.is_file():
        text = ecosystem.read_text(encoding="utf-8")
        if _ECOSYSTEM_START in text and _ECOSYSTEM_END in text:
            ecosystem.write_text(
                _splice_sentinel(text, render_ecosystem_counts(all_stats)),
                encoding="utf-8",
            )
            print(f"Updated {ecosystem} counts block", file=sys.stderr)


if __name__ == "__main__":
    generate()
